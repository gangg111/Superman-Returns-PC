"""gen_projection_regs.py --name <stała>: wejście to ARTIFACTS/catalog.json z listą
'shaders' (type, container_hash w hex, reflection.constants z name/reg/rows/cols);
wyjście to NATIVE_SRC/projection_regs.inc z parami {hash PS, rejestr}, posortowane po hashu.
Ścieżki srpaths podmieniamy na tmp_path, żeby nie nadpisać prawdziwego pliku w port/."""
import json
import runpy
import sys
import types
from pathlib import Path

TOOL = Path(__file__).resolve().parents[2] / "tools" / "shaders" / "gen_projection_regs.py"


def run_tool(tmp_path, monkeypatch, catalog, name):
    artifacts, native = tmp_path / "artifacts", tmp_path / "native"
    artifacts.mkdir()
    native.mkdir()
    (artifacts / "catalog.json").write_text(json.dumps({"shaders": catalog}))
    fake = types.ModuleType("srpaths")
    fake.ARTIFACTS, fake.NATIVE_SRC = artifacts, str(native)
    monkeypatch.setitem(sys.modules, "srpaths", fake)
    monkeypatch.setattr(sys, "argv", [str(TOOL), "--name", name])
    runpy.run_path(str(TOOL), run_name="__main__")
    return (native / "projection_regs.inc").read_bytes()


def const(name, reg, rows=4, cols=4):
    return {"name": name, "reg": reg, "rows": rows, "cols": cols}


def test_only_ps_4x4_constant_rows_sorted_by_hash(tmp_path, monkeypatch):
    catalog = [
        {"type": "ps", "container_hash": "ff00000000000001", "reflection": {"constants": [const("g_InvVP", 12)]}},
        {"type": "ps", "container_hash": "00000000000000AB", "reflection": {"constants": [const("other", 0), const("g_InvVP", 4)]}},
        {"type": "vs", "container_hash": "0000000000000001", "reflection": {"constants": [const("g_InvVP", 8)]}},  # VS: pomijany
        {"type": "ps", "container_hash": "0000000000000002", "reflection": {"constants": [const("g_InvVP", 9, rows=3)]}},  # 3x4: pomijany
        {"type": "ps", "container_hash": "0000000000000003", "reflection": {}},  # brak constants
    ]
    data = run_tool(tmp_path, monkeypatch, catalog, "g_InvVP")
    # źródło: napisane ręcznie; 0xAB < 0xFF00000000000001, hex wielkimi literami na 16 cyfr,
    # końce linii LF (newline='\n')
    expected = (
        b"// Generated by tools/shaders/gen_projection_regs.py - do not edit.\n"
        b"// {pixel shader hash, PS constant register of g_InvVP}\n"
        b"{0x00000000000000ABull, 4},\n"
        b"{0xFF00000000000001ull, 12},\n"
    )
    assert data == expected
