"""Generates port/src/native_renderer/const_range.inc: for every translated shader the number of
float-constant registers it can read (registers 0..n-1), from its HLSL:
  CONST_REL(N)                       -> N
  CONST_REL(N + a0 / aluAddress)     -> 256 when a0 is computed (mova), else N (a0 stays 0)
  #define NAME(INDEX) CONST_REL(B + (INDEX)) used as NAME(k) -> B + k; NAME(<not a literal>) -> 256
Anything not recognised reads as 256 (the whole bank). The renderer uploads only that many
registers of a draw's constants (the copy per draw was a tenth of the render worker).
usage: python tools/shaders/gen_const_range.py"""
import os
import re
import sys


def registers(src):
    dynamic_a0 = any(v.strip() != '0' for v in re.findall(r'\ba0\s*=\s*([^;=]*);', src))
    hi = 0
    for m in re.finditer(r'CONST_REL\(([^()]*(?:\([^()]*\))?[^()]*)\)', src):
        arg = m.group(1).strip()
        if arg == 'INDEX':
            continue  # the macro's own definition
        n = re.fullmatch(r'(\d+)', arg)
        if n:
            hi = max(hi, int(n.group(1)) + 1)
            continue
        n = re.fullmatch(r'(\d+)\s*\+\s*(a0|aluAddress)', arg)
        if n:
            if dynamic_a0:
                return 256
            hi = max(hi, int(n.group(1)) + 1)
            continue
        if re.fullmatch(r'\d+\s*\+\s*\(INDEX\)', arg):
            continue  # a named constant's definition; its uses are counted below
        return 256
    for d in re.finditer(r'#define (\w+)\(INDEX\) CONST_REL\((\d+) \+ \(INDEX\)\)', src):
        name, base = d.group(1), int(d.group(2))
        for u in re.finditer(r'\b' + re.escape(name) + r'\(([^()]*)\)', src):
            arg = u.group(1).strip()
            if arg == 'INDEX':
                continue
            if not re.fullmatch(r'\d+', arg):
                return 256
            hi = max(hi, base + int(arg) + 1)
    return min(hi, 256)


def main():
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    from srpaths import ARTIFACTS, NATIVE_SRC  # noqa: E402
    rows = []
    for name in sorted(os.listdir(ARTIFACTS / 'hlsl')):
        m = re.fullmatch(r'([0-9A-F]{16})\.(vs|ps)\.hlsl', name)
        if not m:
            continue
        src = open(ARTIFACTS / 'hlsl' / name, encoding='utf-8', errors='replace').read()
        rows.append((int(m.group(1), 16), m.group(2) == 'ps', registers(src)))
    rows.sort()
    out = NATIVE_SRC / 'const_range.inc'
    with open(out, 'w', newline='\n') as f:
        f.write('// Generated by tools/shaders/gen_const_range.py; do not edit.\n')
        f.write('// {shader hash, pixel shader, float-constant registers it can read}\n')
        for h, ps, n in rows:
            f.write('{0x%016Xull, %d, %d},\n' % (h, int(ps), n))
    full = sum(1 for r in rows if r[2] == 256)
    print('%d shaders -> %s (%d read the whole bank, median %d registers)' % (
        len(rows), out, full, sorted(r[2] for r in rows)[len(rows) // 2]))


if __name__ == '__main__':
    main()
