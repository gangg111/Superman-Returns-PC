"""The mouse cursor: the game's own S shield (ui.AST SUPERMANICON, 64x64 on a dark
blue square), its background cut away (port/resources/cursor_s.png, cut with
AI Image Studio's remove_background, model lucida, 2026-11-09), cropped to the
shield, made square and scaled to SIZE pixels, written as straight BGRA rows
top-down for CreateIconIndirect. It points with the shield's tip (turned to the
upper left), the hotspot on the tip.

  make_cursor.py   writes port/src/input/cursor_s.inc
"""
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SIZE = 24  # half the first 48 (the user, 2026-11-09: "zmniejsz kursor o połowę")
# The shield's tip (its bottom point) turned to the upper left, as an arrow points
# (the user's request, 2026-11-09): 135 degrees clockwise.
ROTATE = -135


def cursor_pixels(rgba, size=SIZE, rotate=ROTATE):
    """rgba: a PIL RGBA image. Returns (size, BGRA bytes top-down, hotspot x, y):
    the shield turned `rotate` degrees (PIL: counter-clockwise), cropped, in the
    top-left of a square, scaled; the hotspot is its opaque pixel nearest the
    top-left corner, the tip."""
    from PIL import Image

    def crop(im):
        return im.crop(im.getchannel('A').point(lambda a: 255 if a > 16 else 0).getbbox())

    shield = crop(rgba)
    if rotate:
        shield = crop(shield.rotate(rotate, resample=Image.BILINEAR, expand=True))
    side = max(shield.size)
    square = Image.new('RGBA', (side, side), (0, 0, 0, 0))
    square.paste(shield, (0, 0))
    # BOX: no overshoot (LANCZOS rang a flat 200 up to 242 at the shield's edge)
    small = square.resize((size, size), Image.BOX)
    out = bytearray()
    hot, best = (0, 0), None
    for i, (r, g, b, a) in enumerate(small.getdata()):
        out += bytes((b, g, r, a))
        x, y = i % size, i // size
        if a > 128 and (best is None or x + y < best):
            hot, best = (x, y), x + y
    return size, bytes(out), hot[0], hot[1]


def write_inc(path, size, bgra, hot_x, hot_y):
    with open(path, 'w', newline='\n') as f:
        f.write('// Generated by tools/ui/make_cursor.py from port/resources/cursor_s.png; do not edit.\n')
        f.write('constexpr int kCursorSize = %d, kCursorHotX = %d, kCursorHotY = %d;\n' % (size, hot_x, hot_y))
        f.write('constexpr unsigned char kCursorBgra[] = {\n')
        for i in range(0, len(bgra), 16):
            f.write('    ' + ', '.join('%d' % v for v in bgra[i:i + 16]) + ',\n')
        f.write('};\n')


if __name__ == '__main__':
    from PIL import Image
    src = os.path.join(ROOT, 'port', 'resources', 'cursor_s.png')
    size, bgra, hx, hy = cursor_pixels(Image.open(src).convert('RGBA'))
    out = os.path.join(ROOT, 'port', 'src', 'input', 'cursor_s.inc')
    write_inc(out, size, bgra, hx, hy)
    print('%dx%d cursor -> %s' % (size, size, out))
