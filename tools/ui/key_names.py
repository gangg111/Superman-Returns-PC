"""The key names the keyboard bindings (keybind_*) accept, read from the SDK's
table (src/ui/keybinds.cpp: {"Name", VirtualKey::kX}) and its key codes
(include/rex/ui/virtual_key.h: kX = 0x..). One name a code: the first one in
the table (the table is an unordered_map in C++, so its own reverse lookup
picks any of the names for a code with two, e.g. Return / NumpadEnter).

Used by build_ui_mod.py (the Keys Mapping screen's texts, KEYNAME_<code>) and
to write port/src/input/key_names.inc (the codes back to names when a key is
captured):

  key_names.py   writes port/src/input/key_names.inc
"""
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SDK = os.path.join(ROOT, '.tools', 'rexglue-sdk-full')


def parse(keybinds_cpp, virtual_key_h):
    """[(code, name)] in table order, one entry a code."""
    codes = {}
    for m in re.finditer(r'\b(k\w+)\s*=\s*(0x[0-9A-Fa-f]+|\d+)\s*,', virtual_key_h):
        codes[m.group(1)] = int(m.group(2), 0)
    out, seen = [], set()
    table = keybinds_cpp[keybinds_cpp.index('kKeyNames'):]
    table = table[:table.index('};')]
    for m in re.finditer(r'\{"([^"]+)",\s*VirtualKey::(k\w+)\}', table):
        code = codes.get(m.group(2))
        if code is None or code in seen:
            continue
        seen.add(code)
        out.append((code, m.group(1)))
    return out


def sdk_key_names():
    with open(os.path.join(SDK, 'src', 'ui', 'keybinds.cpp'), encoding='utf-8') as f:
        cpp = f.read()
    with open(os.path.join(SDK, 'include', 'rex', 'ui', 'virtual_key.h'), encoding='utf-8') as f:
        h = f.read()
    return parse(cpp, h)


def write_inc(path, names):
    with open(path, 'w', newline='\n') as f:
        f.write('// Generated by tools/ui/key_names.py from the SDK\'s key table; do not edit.\n')
        f.write('// {virtual key code, the name keybind_* uses for it}\n')
        for code, name in names:
            f.write('{0x%02X, "%s"},\n' % (code, name))


if __name__ == '__main__':
    names = sdk_key_names()
    out = os.path.join(ROOT, 'port', 'src', 'input', 'key_names.inc')
    write_inc(out, names)
    print('%d key names -> %s' % (len(names), out))
